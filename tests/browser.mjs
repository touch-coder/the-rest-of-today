// Optional browser smoke test. Set PLAYWRIGHT_MODULE and CHROME_EXECUTABLE for your environment.
import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { today, addDays, createState, saveRecord, confirmDay, backup } from '../shared/domain.js';
const modulePath=process.env.PLAYWRIGHT_MODULE||'/Users/mac/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
const {chromium}=await import(pathToFileURL(modulePath).href);
const browser=await chromium.launch({executablePath:process.env.CHROME_EXECUTABLE||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const context=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,acceptDownloads:true});
const page=await context.newPage();
const errors=[];page.on('pageerror',error=>errors.push(error.message));
const current=today(),previous=addDays(current,-1);
const base=process.env.APP_URL||'http://localhost:5173';
const output=new URL('../artifacts/',import.meta.url);
await mkdir(output,{recursive:true});
try{
  await page.goto(base);
  await page.locator('[data-action="add-record"][data-type="night"]').click();
  await page.locator('#record-form [name="start"]').fill(`${previous}T23:00`);
  await page.locator('#record-form [name="end"]').fill(`${current}T07:00`);
  await page.locator('#record-form [name="note"]').fill('<script>unsafe</script> 中途醒来一次');
  await page.locator('#record-form [type="submit"]').click();
  await page.waitForFunction(()=>!document.querySelector('#record-dialog').open);
  await page.locator('[data-action="confirm-day"]').click();
  await page.waitForFunction(()=>document.querySelector('.day-panel .badge').textContent==='已确认完整');
  assert.equal(await page.locator('.sleep-card.night>strong').textContent(),'8 小时');
  await page.locator('[data-action="add-record"][data-type="nap"]').click();
  await page.locator('#record-form [type="submit"]').click();
  await page.waitForFunction(()=>!document.querySelector('#record-dialog').open);
  assert.equal(await page.locator('.day-panel .badge').textContent(),'待确认完整');
  await page.locator('[data-action="confirm-day"]').click();
  await page.locator('.sleep-card.nap [data-action="delete-record"]').click();
  await page.locator('#confirm-dialog button[value="confirm"]').click();
  await page.waitForSelector('[data-action="undo"]');
  assert.equal(await page.locator('.day-panel .badge').textContent(),'待确认完整');
  await page.locator('[data-action="undo"]').click();
  assert.equal(await page.locator('.day-panel .badge').textContent(),'已确认完整');
  assert.equal(await page.locator('.sleep-card.nap>strong').textContent(),'0 小时 30 分');
  const stored=JSON.parse(await page.evaluate(()=>localStorage.getItem('sleeping-table:v1')));
  assert.equal(stored.records.length,2);
  await page.reload();
  assert.equal(await page.locator('.day-panel .badge').textContent(),'已确认完整');
  console.log('PASS mobile record, confirm, add, delete, undo, persistence, escaped notes');

  // Missing night remains missing even when a nap exists.
  await page.locator('#selected-date').fill(previous);
  await page.locator('[data-action="add-record"][data-type="nap"]').click();
  await page.locator('#record-form [type="submit"]').click();
  await page.locator('#confirm-dialog button[value="confirm"]').click();
  await page.waitForFunction(()=>!document.querySelector('#record-dialog').open);
  assert.match(await page.locator('.day-panel .badge').textContent(),/缺少夜间/);
  assert.equal(await page.locator('[data-action="confirm-day"]').count(),0);
  assert.equal(await page.locator('[data-action="confirm-zero"]').count(),0);
  console.log('PASS missing-night rule and earlier-date prompt');

  await page.locator('.mobile-nav [data-page="settings"]').click();
  const downloadPromise=page.waitForEvent('download');
  await page.locator('[data-action="export-json"]').click();
  const download=await downloadPromise;
  const text=await readFile(await download.path(),'utf8');
  assert.equal(JSON.parse(text).data.records.length,3);
  const importState=createState();importState.startDate=addDays(current,-2);
  let incoming=saveRecord(importState,{id:'imported',type:'night',start:`${addDays(current,-3)}T23:00`,end:`${addDays(current,-2)}T07:00`,note:'备份记录'});
  incoming=confirmDay(incoming,addDays(current,-2),false,current);
  await page.locator('#import-file').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(backup(incoming))});
  await page.waitForFunction(()=>document.querySelector('#import-dialog').open);
  await page.locator('[data-action="commit-import"]').click();
  await page.waitForFunction(()=>!document.querySelector('#import-dialog').open);
  assert.equal(JSON.parse(await page.evaluate(()=>localStorage.getItem('sleeping-table:v1'))).records.length,4);
  console.log('PASS JSON download, import preview and merge');

  await page.locator('.mobile-nav [data-page="report"]').click();
  assert.equal(await page.locator('h1').textContent(),'睡眠总结');
  assert.equal(await page.locator('[data-action="report-week"]').textContent(),'每周总结');
  await page.locator('[data-action="report-month"]').click();
  assert.equal(await page.locator('[data-action="report-month"]').textContent(),'每月总结');
  assert.equal(await page.locator('.stats-grid .stat-card').count(),5);
  assert.match(await page.locator('[data-stat="recorded-days"] strong').textContent(),/^3\s*天$/);
  await page.locator('.mobile-nav [data-page="calendar"]').click();
  assert.ok(await page.locator('.calendar-day').count()>=28);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false);
  await page.evaluate(()=>document.querySelector('#toast').classList.remove('visible'));
  await page.screenshot({path:new URL('mobile-calendar.png',output).pathname,fullPage:true});
  await page.locator('.mobile-nav [data-page="home"]').click();
  await page.locator('#selected-date').fill(current);
  await page.screenshot({path:new URL('mobile-home.png',output).pathname,fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.waitForTimeout(200);
  await page.screenshot({path:new URL('desktop-home.png',output).pathname,fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false);
  console.log('PASS mobile and desktop layouts, report, calendar');

  await page.evaluate(()=>navigator.serviceWorker.ready);
  await page.waitForFunction(()=>!!navigator.serviceWorker.controller);
  await context.setOffline(true);
  await page.reload();
  await page.waitForSelector('.sleep-card.night');
  assert.equal(await page.locator('.sleep-card.night>strong').textContent(),'8 小时');
  await page.locator('.sleep-card.night [data-action="edit-record"]').click();
  await page.locator('#record-form [name="end"]').fill(`${current}T07:15`);
  await page.locator('#record-form [type="submit"]').click();
  await page.waitForFunction(()=>!document.querySelector('#record-dialog').open);
  assert.equal(await page.locator('.sleep-card.night>strong').textContent(),'8 小时 15 分');
  await page.reload();
  assert.equal(await page.locator('.sleep-card.night>strong').textContent(),'8 小时 15 分');
  assert.deepEqual(errors,[]);
  console.log('PASS offline reload, edit and persistent save; no browser errors');

  const fallbackPage=await browser.newPage();
  await fallbackPage.goto(new URL('../web/index.html',import.meta.url).href);
  assert.match(await fallbackPage.locator('#boot-message').textContent(),/直接打开 HTML/);
  await fallbackPage.close();
  const corruptContext=await browser.newContext({viewport:{width:360,height:800}});
  await corruptContext.addInitScript(()=>localStorage.setItem('sleeping-table:v1','{broken'));
  const corruptPage=await corruptContext.newPage();
  await corruptPage.goto(base);
  await corruptPage.waitForSelector('.banner.error');
  assert.equal(await corruptPage.evaluate(()=>localStorage.getItem('sleeping-table:v1')),'{broken');
  await corruptPage.locator('.mobile-nav [data-page="settings"]').click();
  assert.equal(await corruptPage.locator('[data-action="export-raw"]').count(),1);
  assert.equal(await corruptPage.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false);
  await corruptContext.close();
  console.log('PASS direct-file fallback, damaged-storage recovery and 360px layout');
}finally{await browser.close();}
